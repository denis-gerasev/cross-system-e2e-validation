"""Minimal Page Object for the one flow this suite exercises: add a product
to the cart and read back the USD subtotal / checkout confirmation.

This intentionally does not cover the whole app (the size filter, multiple
cart lines, removing items, etc.) - it only needs to support
`tests/e2e/test_crypto_checkout.py`. For a full Page-Object-Model suite of
this same app (every component, every interaction), see the standalone
`react-shopping-cart-e2e` project; its locator choices were verified against
this app's actual markup and are reused here.

The app has no `data-testid`s on the elements used below, and its CSS class
names are generated by styled-components, so locators use role, text and
DOM structure instead of classes - see the comments inline.
"""
from __future__ import annotations

import re
from decimal import Decimal

from playwright.sync_api import Dialog, Page, expect

_MONEY = re.compile(r"(\d[\d,]*\.\d{2})")


def _parse_money(text: str) -> Decimal:
    """Extract a `1,234.56`-style amount from UI text (e.g. "$ 10.90")."""
    match = _MONEY.search(text)
    if not match:
        raise ValueError(f"No money amount found in {text!r}")
    return Decimal(match.group(1).replace(",", ""))


class ShoppingCartPage:
    """Wraps the single page of the app: the product grid and the slide-in cart."""

    def __init__(self, page: Page) -> None:
        self.page = page

        # A product tile is the <div> that directly contains an "Add to
        # cart" button; scope to one tile by filtering on its title text.
        self._cards = page.locator('div:has(> button:text-is("Add to cart"))')

        # Cart toggle: shows a quantity badge (title="Products in cart
        # quantity") when closed, becomes an "X" button when open.
        self._close_button = page.get_by_role("button", name="X", exact=True)

        self._checkout_button = page.get_by_role("button", name="Checkout")
        # Footer markup: <div><p>SUBTOTAL</p><div><p>$ 0.00</p><p>...</p></div>
        # <button>Checkout</button></div> - the subtotal is the first <p>
        # inside the <div> that is a sibling of the Checkout button.
        footer = page.locator('div:has(> button:text-is("Checkout"))')
        self._subtotal = footer.locator(":scope > div > p").first

    # ---- actions -----------------------------------------------------------
    def add_to_cart(self, title: str) -> None:
        """Add one unit of the product titled `title`. Leaves the cart open,
        as the app does after every add."""
        if self._close_button.is_visible():
            self._close_button.click()  # the open cart overlays the grid

        card = self._cards.filter(has=self.page.get_by_text(title, exact=True))
        card.get_by_role("button", name="Add to cart", exact=True).click()
        expect(self._checkout_button).to_be_visible()

    # ---- reads -------------------------------------------------------------
    def subtotal(self) -> Decimal:
        """The cart's current USD subtotal (cart must be open)."""
        expect(self._subtotal).to_be_visible()
        return _parse_money(self._subtotal.inner_text())

    # ---- checkout ------------------------------------------------------------
    def checkout(self) -> str:
        """Click Checkout and return the `window.alert` text it raises.

        The app uses `window.alert`, which freezes the page until handled,
        so the dialog handler is registered *before* the click.
        """
        messages: list[str] = []

        def _accept(dialog: Dialog) -> None:
            messages.append(dialog.message)
            dialog.accept()

        self.page.once("dialog", _accept)
        self._checkout_button.click()

        if not messages:
            raise AssertionError("Expected a checkout confirmation dialog, got none")
        return messages[0]
